import { Injectable, Signal } from "@angular/core";
import { AuthService } from "./auth.service";
import { DatabaseService } from "./database.service";
import { StorageService } from "./storage.service";
import { GenerationType } from "@shared/types/generation";
import { TaskStatus } from "@shared/types/task";

@Injectable({
  providedIn: "root",
})
export class DocumentsService {
  uid?: string;
  orgId = "all";

  constructor(
    private auth: AuthService,
    private db: DatabaseService,
    private storage: StorageService
  ) {
    this.uid = this.auth.user()?.uid;
  }

  // Create and upload a new document for the current user.
  // This pushes the document and creates a task in the RTDB,
  // and uploads the actual file to storage.
  uploadDocumentAndCreateTask = async (filename: string, buffer: Buffer) => {
    if (!this.uid) {
      console.log(`Cannot upload document: uid is ${this.uid}\n`);
      return;
    }

    // Upload document info to RTDB.
    const doc = {
      // note: `doc` follows Document interface, other than not having an `id` attribute.
      // the `id` is auto-generated by `this.db.push()`.
      uid: this.uid,
      orgId: this.orgId,
      timestamp: Date.now(),
      filename: filename,
    };
    const documentId = await this.db.push(
      `documents/${this.orgId}/${this.uid}`,
      doc,
    );

    if (!documentId) {
      console.log("Failed to create document.\n");
      return;
    }

    // Upload document contents to storage.
    await this.storage.uploadBytes(`documents/${this.orgId}/${this.uid}/${documentId}.pdf`, buffer);

    // Upload task to RTDB. We do this last, because this upload triggers Firebase functions
    // (which need everything else to be done already).
    const task = {
      // note: `task` follows Task interface, other than not having an `id` attribute.
      // just as with `doc`, this `id` will be auto-generated by `this.db.push()`.
      type: GenerationType.SUMMARY,
      status: TaskStatus.UPLOADING,
      documentId: documentId,
      uid: this.uid,
      orgId: this.orgId,
      timestamp: Date.now(),
    };
    return this.db.push(`tasks`, task);
  };

  // Delete the RTDB and storage entry for the current document.
  // TODO: note - this is not ideal, since I'm not deleting the associated Task.
  deleteDocument = (documentId: string) => {
    console.log("deleteDocument called with id:", documentId);

    this.db.remove(`${this.orgId}/${this.uid}/${documentId}`);
    this.storage.deleteObject(`${this.orgId}/${this.uid}/${documentId}.pdf`);
  };
}
